export type DirreRequestGroup = typeof DIRRE_REQUEST_GROUPS[number]['id'];

export interface AtoDetalhes {
  id: string;
  label: string;
  categoria: string;
  group: DirreRequestGroup;
  sourceRow: number;
}

const aliases: Record<string, string> = {
  'Licença Prévia (LP)': 'licencas-02',
  'Licença Prévia - LP': 'licencas-02',
  'Licença de Instalação (LI) com ampliação': 'licencas-03',
  'Licença de Instalação- LI': 'licencas-03',
  'Licença de Operação (LO)': 'licencas-04',
  'Licença de operação - LO': 'licencas-04',
  'Licença Unificada (LU)': 'licencas-05',
  'Licença Ambiental Única-LAU': 'licencas-05',
  'Autorização Ambiental (AA)': 'autorizacoes-04',
  'Autorização Ambiental - AA': 'autorizacoes-04',
  'Autorização de Supressão de Vegetação - ASV': 'autorizacoes-05',
  "Outorga de uso derecurso hídrico": "outorga-02",
  "Alteração de Outorga dedireito de uso derecursos hídrico": "outorga-03",
  "Declaração de Reservade disponibilidadehídrica": "outorga-04",
  "Outorga Preventiva deuso de recurso hídrico": "outorga-05",
  "Autorização paraperfuração de poço": "outorga-08",
  "Dispensa de Outorga dedireito de uso de recursohídrico": "outorga-09",
};

export function dirreRequestValue(id: string): string {
  return id;
}

export function dirreRequest(value: string) {
  const mappedId = aliases[value] || value;
  const entries = DIRRE_REQUEST_GROUPS.flatMap((g) => [...g.entries]);
  return entries.find((a) => a.id === mappedId) || entries.find((a) => a.label === value);
}

export function dirreRequestLabel(value: string): string {
  return dirreRequest(value)?.label || value || 'Não selecionado';
}

export function getAtoDetails(value: string): AtoDetalhes | undefined {
  if (!value) return undefined;
  const item = dirreRequest(value);
  if (!item) return undefined;
  const catLabel = DIRRE_REQUEST_GROUPS.find((g) => g.id === item.group)?.label || 'Licenças';
  return {
    id: item.id,
    label: item.label,
    categoria: catLabel,
    group: item.group,
    sourceRow: item.sourceRow,
  };
}
