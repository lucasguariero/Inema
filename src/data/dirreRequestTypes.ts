export function dirreRequestValue(id: string): string {
  return id;
}

export function dirreRequest(value: string) {
  const id = aliases[value] || value;
  return DIRRE_REQUEST_GROUPS.flatMap(g => [...g.entries]).find(a => a.id === id || a.label === value);
}

export function dirreRequestLabel(value: string): string {
  return dirreRequest(value)?.label || value || 'Não selecionado';
}

export function getAtoDetails(value: string): AtoDetalhes | undefined {
  if (!value) return undefined;
  const item = dirreRequest(value);
  const id = item?.id || aliases[value] || value;
  const meta = ATO_METADATA[id];
  const catLabel = item ? (DIRRE_REQUEST_GROUPS.find(g => g.id === item.group)?.label || 'Licenças') : 'Licenças';

  if (meta) {
    return {
      id,
      sigla: meta.sigla,
      nome: meta.nome,
      categoria: catLabel,
      taxaBase: meta.taxaBase,
      descricao: meta.descricao,
      legislacao: meta.legislacao,
    };
  }

  if (item) {
    return {
      id: item.id,
      sigla: item.id.split('-')[0].slice(0, 3).toUpperCase(),
      nome: item.label,
      categoria: catLabel,
      taxaBase: 'Sob enquadramento (Decreto Estadual nº 14.024/2012)',
      descricao: item.label,
      legislacao: 'Lei Estadual nº 10.431/2006 e Regulamento SEIA (Decreto Estadual nº 14.024/2012)',
    };
  }

  return undefined;
}
